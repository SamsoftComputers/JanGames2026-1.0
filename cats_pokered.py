RATE = 22050
def pulse(f, d, duty=0.5, v=0.12):
    if f==0: return [0.0]*int(RATE*d)
    s, per = [], RATE/f
    for i in range(int(RATE*d)): s.append(v if (i%per)/per<duty else -v)
    return s

def mksnd(s):
    i = [int(max(-32767,min(32767,x*32767))) for x in s]
    st = []
    for x in i: st.extend([x,x])
    return pygame.mixer.Sound(buffer=array.array('h',st))

