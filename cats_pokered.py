def can_walk(mid, x, y):
    if mid not in MAPS: return False
    m = MAPS[mid]
    d = m['data']
    if y<0 or y>=len(d) or x<0 or x>=len(d[0]): return False
    t = d[y][x]
    return TILES.get(t,(None,None,False,False))[2]

def check_enc(mid, x, y):
    if mid not in MAPS: return None
    m = MAPS[mid]
    d = m['data']
    if y<0 or y>=len(d) or x<0 or x>=len(d[0]): return None
    t = d[y][x]
    if not TILES.get(t,(None,None,False,False))[3]: return None
    enc = m.get('enc',{})
    rate = enc.get('rate',0)
    if random.randint(1,100) <= rate:
        gr = enc.get('grass',[])
        if gr:
            dex, lvl = random.choice(gr)
            lvl = max(2, lvl + random.randint(-2,2))
            return Pokemon(dex, lvl)
    return None

def check_conn(mid, x, y):
    if mid not in MAPS: return None
    m = MAPS[mid]
    d = m['data']
    conn = m.get('conn',{})
    if y<=0 and 'n' in conn: return conn['n']
    if y>=len(d)-1 and 's' in conn: return conn['s']
    if x<=0 and 'w' in conn: return conn['w']
    if x>=len(d[0])-1 and 'e' in conn: return conn['e']
    return None

