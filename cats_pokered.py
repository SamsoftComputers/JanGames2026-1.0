# ═══════════════════════════════════════════════════════════════════════════════
def main():
    running = True
    cooldown = 0
    save_msg, save_timer = "", 0
    
    while running:
        for ev in pygame.event.get():
            if ev.type == pygame.QUIT:
                running = False
            elif ev.type == pygame.KEYDOWN:
                if G.state == 'TITLE':
                    if ev.key == pygame.K_SPACE:
                        SFX['sel'].play()
                        sd = load_game()
                        if sd:
                            G.apply_save(sd)
                        else:
                            new_game()
                elif G.state == 'OVERWORLD':
                    if ev.key in [pygame.K_ESCAPE, pygame.K_RETURN]:
                        G.state = 'MENU'
                        G.menu_sel = 0
                        SFX['sel'].play()
                elif G.state == 'MENU':
                    if ev.key == pygame.K_ESCAPE:
                        G.state = 'OVERWORLD'
                        SFX['sel'].play()
                    elif ev.key == pygame.K_UP:
                        G.menu_sel = (G.menu_sel - 1) % 5
                        SFX['mov'].play()
                    elif ev.key == pygame.K_DOWN:
                        G.menu_sel = (G.menu_sel + 1) % 5
                        SFX['mov'].play()
                    elif ev.key in [pygame.K_SPACE, pygame.K_RETURN, pygame.K_z]:
                        SFX['sel'].play()
                        if G.menu_sel == 2:  # SAVE
                            if save_game(G):
                                save_msg, save_timer = "GAME SAVED!", 120
                            else:
                                save_msg, save_timer = "SAVE FAILED!", 120
                            G.state = 'SAVE_MSG'
                        elif G.menu_sel == 3:  # LOAD
                            sd = load_game()
                            if sd:
                                G.apply_save(sd)
                                save_msg, save_timer = "GAME LOADED!", 120
                            else:
                                save_msg, save_timer = "NO SAVE FILE!", 120
                            G.state = 'SAVE_MSG'
                        elif G.menu_sel == 4:  # EXIT
                            G.state = 'OVERWORLD'
                elif G.state == 'SAVE_MSG':
                    if ev.key in [pygame.K_SPACE, pygame.K_RETURN, pygame.K_z]:
                        G.state = 'OVERWORLD'
                        save_timer = 0
                elif G.state == 'BATTLE':
                    r = G.battle.input(ev.key)
                    if r == 'RUN':
                        G.state = 'OVERWORLD'
                        G.battle = None
                    elif G.battle and G.battle.state == 'WIN':
                        G.state = 'OVERWORLD'
                        G.battle = None
                    elif G.battle and G.battle.state == 'LOSE':
                        for p in G.party: p.heal()
                        G.map_id, G.x, G.y = 'PALLET_TOWN', 10, 14
                        G.state = 'OVERWORLD'
                        G.battle = None
        
