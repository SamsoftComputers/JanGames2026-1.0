# POKEMON CLASS
# ═══════════════════════════════════════════════════════════════════════════════
class Pokemon:
    def __init__(self, dex, lvl, nick=None):
        d = POKEMON.get(dex, POKEMON[1])
        self.dex, self.lvl = dex, lvl
        self.name = nick or d[0]
        self.species, self.types = d[0], d[1]
        self.base = d[2]
        self.ivs = [random.randint(0,15) for _ in range(6)]
        self.evs = [0]*6
        self.calc_stats()
        self.hp = self.maxhp
        self.moves, self.pp, self.maxpp = [], [], []
        for lv in sorted(d[7].keys()):
            if lv <= lvl:
                for m in d[7][lv]:
                    if m in MOVES:
                        if len(self.moves) < 4:
                            self.moves.append(m)
                            self.pp.append(MOVES[m][3])
                            self.maxpp.append(MOVES[m][3])
                        else:
                            i = random.randint(0,3)
                            self.moves[i], self.pp[i], self.maxpp[i] = m, MOVES[m][3], MOVES[m][3]
        self.status = None
        self.stages = {s:0 for s in ['ATK','DEF','SPA','SPD','SPE','ACC','EVA']}
        self.exp = lvl**3
    
    def calc_stats(self):
        self.maxhp = int(((self.base[0]+self.ivs[0])*2+self.evs[0]**0.5/4)*self.lvl/100)+self.lvl+10
        for i,s in enumerate(['atk','def_','spa','spd','spe']):
            setattr(self,s,int(((self.base[i+1]+self.ivs[i+1])*2+self.evs[i+1]**0.5/4)*self.lvl/100)+5)
    
    def get_stat(self,s):
        base = getattr(self,s.lower().replace('def','def_').replace('spd','spd').replace('spa','spa').replace('spe','spe'),self.atk)
        st = self.stages.get(s,0)
        return int(base*(2+st)/2) if st>=0 else int(base*2/(2-st))
    
    def gain_exp(self,amt):
        self.exp += amt
        lv = False
        while self.exp >= (self.lvl+1)**3 and self.lvl<100:
            self.lvl += 1
            old = self.maxhp
            self.calc_stats()
            self.hp += self.maxhp - old
            lv = True
            d = POKEMON[self.dex]
            if d[5] and self.lvl >= d[5]:
                self.evolve()
        return lv
    
    def evolve(self):
        d = POKEMON[self.dex]
        if d[6]:
            self.dex = d[6]
            nd = POKEMON[self.dex]
            if self.name == d[0]: self.name = nd[0]
            self.species, self.types, self.base = nd[0], nd[1], nd[2]
            self.calc_stats()
    
    def heal(self):
        self.hp, self.status = self.maxhp, None
        for i in range(len(self.pp)): self.pp[i] = self.maxpp[i]
    
    def fainted(self): return self.hp <= 0
    
    def to_dict(self):
        return {'dex':self.dex,'lvl':self.lvl,'name':self.name,'hp':self.hp,'exp':self.exp,
                'ivs':self.ivs,'evs':self.evs,'moves':self.moves,'pp':self.pp,'maxpp':self.maxpp,'status':self.status}
    
    @classmethod
    def from_dict(cls, d):
        p = cls(d['dex'], d['lvl'], d.get('name'))
        p.hp, p.exp = d.get('hp',p.maxhp), d.get('exp',p.exp)
