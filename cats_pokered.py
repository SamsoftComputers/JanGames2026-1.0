class Battle:
    def __init__(self, wild=None, trainer=None, tname=None):
        self.player = G.party[0] if G.party else None
        self.enemy = wild
        self.trainer, self.tname = trainer, tname
        self.tparty, self.tidx = [], 0
        self.wild = trainer is None
        if trainer:
            self.tparty = [Pokemon(d,l) for d,l in trainer]
            self.enemy = self.tparty[0]
        self.state, self.midx, self.mvidx = 'INTRO', 0, 0
        self.msg, self.msgidx = [], 0
        self.prize = 0
    
    def start(self):
        if self.wild: self.msg = [f"Wild {self.enemy.name} appeared!"]
        else: self.msg = [f"{self.tname} wants to fight!", f"{self.tname} sent out {self.enemy.name}!"]
        self.state = 'INTRO'
    
    def input(self, k):
        if self.state in ['INTRO','MSG','RES']:
            if k in [pygame.K_SPACE, pygame.K_RETURN, pygame.K_z]:
                self.msgidx += 1
                if self.msgidx >= len(self.msg):
                    if self.state=='INTRO': self.state='MENU'
                    elif self.state=='RES': return self.check_end()
                    else:
                        r = self.check_end()
                        if r: return r
                    self.msg, self.msgidx = [], 0
        elif self.state == 'MENU':
            if k==pygame.K_UP: self.midx=(self.midx-2)%4; SFX['mov'].play()
            elif k==pygame.K_DOWN: self.midx=(self.midx+2)%4; SFX['mov'].play()
            elif k==pygame.K_LEFT: self.midx=(self.midx-1)%4; SFX['mov'].play()
            elif k==pygame.K_RIGHT: self.midx=(self.midx+1)%4; SFX['mov'].play()
            elif k in [pygame.K_SPACE, pygame.K_RETURN, pygame.K_z]:
                SFX['sel'].play()
                if self.midx==0: self.state='MOVE'; self.mvidx=0
                elif self.midx==1: self.try_catch()
                elif self.midx==3:
                    if self.try_run(): return 'RUN'
        elif self.state == 'MOVE':
            mm = len(self.player.moves)
            if k==pygame.K_UP: self.mvidx=(self.mvidx-2)%mm; SFX['mov'].play()
            elif k==pygame.K_DOWN: self.mvidx=(self.mvidx+2)%mm; SFX['mov'].play()
            elif k==pygame.K_LEFT: self.mvidx=(self.mvidx-1)%mm; SFX['mov'].play()
            elif k==pygame.K_RIGHT: self.mvidx=(self.mvidx+1)%mm; SFX['mov'].play()
            elif k in [pygame.K_SPACE, pygame.K_RETURN, pygame.K_z]:
                SFX['sel'].play()
                self.do_turn(self.player.moves[self.mvidx])
            elif k in [pygame.K_ESCAPE, pygame.K_x]:
                self.state='MENU'; SFX['sel'].play()
        return None
    
    def do_turn(self, pm):
        ps, es = self.player.get_stat('SPE'), self.enemy.get_stat('SPE')
        em = random.choice(self.enemy.moves) if self.enemy.moves else 'TACKLE'
        self.msg = []
        if ps >= es:
            self.do_move(self.player, self.enemy, pm, True)
            if not self.enemy.fainted(): self.do_move(self.enemy, self.player, em, False)
        else:
            self.do_move(self.enemy, self.player, em, False)
            if not self.player.fainted(): self.do_move(self.player, self.enemy, pm, True)
        self.state, self.msgidx = 'MSG', 0
    
    def do_move(self, atk, df, mv, isp):
        if mv not in MOVES: return
        m = MOVES[mv]
        mtype, pwr, acc, pp, cat, eff = m
        pf = atk.name if isp else f"Foe {atk.name}"
        self.msg.append(f"{pf} used {mv}!")
        if random.randint(1,100) > acc:
            self.msg.append("But it missed!")
            return
        if pwr > 0:
            a = atk.get_stat('ATK' if cat=='PHY' else 'SPA')
            d = df.get_stat('DEF' if cat=='PHY' else 'SPD')
            eff_m = type_eff(mtype, df.types)
            stab = 1.5 if mtype in atk.types else 1.0
            rnd = random.randint(85,100)/100
            dmg = int(((2*atk.lvl/5+2)*pwr*a/d/50+2)*stab*eff_m*rnd)
            dmg = max(1, dmg)
            df.hp = max(0, df.hp - dmg)
            SFX['hit'].play()
            if eff_m > 1: self.msg.append("Super effective!")
            elif 0 < eff_m < 1: self.msg.append("Not very effective...")
            elif eff_m == 0: self.msg.append("It had no effect...")
    
    def try_run(self):
        if not self.wild:
            self.msg, self.state = ["Can't run!"], 'MSG'
            return False
        if random.randint(0,255) < (self.player.spe*32)//(self.enemy.spe//4+1)+30:
            return True
        self.msg, self.state = ["Can't escape!"], 'MSG'
        return False
    
    def try_catch(self):
        if not self.wild:
            self.msg, self.state = ["Can't catch trainer's Pokemon!"], 'MSG'
            return
        if G.bag.get('POKE BALL',0) <= 0:
            self.msg, self.state = ["No Poke Balls!"], 'MSG'
            return
        G.bag['POKE BALL'] -= 1
        self.msg = ["You threw a POKE BALL!"]
        cr = POKEMON[self.enemy.dex][4]
        hpf = (3*self.enemy.maxhp - 2*self.enemy.hp) / (3*self.enemy.maxhp)
        cv = cr * hpf
        if random.randint(0,255) < cv:
            self.msg.append(f"Gotcha! {self.enemy.name} was caught!")
            SFX['catch'].play()
            if len(G.party) < 6: G.party.append(self.enemy)
            else:
                G.pc[0].append(self.enemy)
                self.msg.append(f"{self.enemy.name} sent to PC!")
            G.caught.add(self.enemy.dex)
            self.state = 'WIN'
        else:
            self.msg.append("Oh no! It broke free!")
        self.state = 'MSG'
    
    def check_end(self):
        if self.state == 'WIN': return 'WIN'
        if self.enemy.fainted():
            exp = (self.enemy.lvl * POKEMON[self.enemy.dex][3]) // 7
            lv = self.player.gain_exp(exp)
            self.msg = [f"{self.enemy.name} fainted!", f"{self.player.name} gained {exp} EXP!"]
            if lv:
                self.msg.append(f"{self.player.name} grew to Lv.{self.player.lvl}!")
                SFX['lvl'].play()
            if self.trainer and self.tidx < len(self.tparty)-1:
                self.tidx += 1
                self.enemy = self.tparty[self.tidx]
                self.msg.append(f"{self.tname} sent out {self.enemy.name}!")
                self.state = 'MSG'
                return None
            self.state = 'WIN'
            return None
        if self.player.fainted():
            self.msg = [f"{self.player.name} fainted!"]
            alive = [p for p in G.party if not p.fainted()]
            if not alive:
                self.msg.append("You blacked out!")
                self.state = 'LOSE'
            else:
                for i,p in enumerate(G.party):
                    if not p.fainted():
                        G.party[0], G.party[i] = G.party[i], G.party[0]
                        self.player = G.party[0]
                        self.msg.append(f"Go! {self.player.name}!")
                        self.state = 'MSG'
                        break
            return None
        self.state = 'MENU'
        return None
    
    def draw(self, s):
        s.fill(WHITE)
        if self.enemy:
            draw_pkmn(s, self.enemy.dex, 100, 20, 2)
            draw_box(s, 5, 10, 75, 32)
