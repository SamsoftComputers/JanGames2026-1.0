        if G.state == 'OVERWORLD' and cooldown == 0:
            keys = pygame.key.get_pressed()
            dx, dy = 0, 0
            if keys[pygame.K_UP]: dy, G.face = -1, 'up'
            elif keys[pygame.K_DOWN]: dy, G.face = 1, 'down'
            elif keys[pygame.K_LEFT]: dx, G.face = -1, 'left'
            elif keys[pygame.K_RIGHT]: dx, G.face = 1, 'right'
            if dx or dy:
                nx, ny = G.x+dx, G.y+dy
                conn = check_conn(G.map_id, nx, ny)
                if conn:
                    G.map_id, G.x, G.y = conn
                    cooldown = 8
                elif can_walk(G.map_id, nx, ny):
                    G.x, G.y = nx, ny
                    cooldown = 8
                    wild = check_enc(G.map_id, G.x, G.y)
                    if wild:
                        G.seen.add(wild.dex)
                        G.battle = Battle(wild)
                        G.battle.start()
                        G.state = 'BATTLE'
                else:
                    SFX['bump'].play()
                    cooldown = 8
        
        if cooldown > 0: cooldown -= 1
        if save_timer > 0:
            save_timer -= 1
            if save_timer == 0 and G.state == 'SAVE_MSG':
                G.state = 'OVERWORLD'
        
        G.frame += 1
        G.playtime += 1
        
